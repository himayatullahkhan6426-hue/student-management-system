// Helper to convert scheme to editable semesters state
export function createSemestersFromScheme(scheme, departmentId = "se") {
  return scheme.map((sem, sIdx) => ({
    id: `scheme-${departmentId}-sem-${sIdx + 1}`,
    name: sem.name,
    subjects: sem.courses.map((c, cIdx) => ({
      id: `c-${departmentId}-${sIdx + 1}-${cIdx + 1}`,
      code: c.code,
      title: c.title,
      credits: c.credits,
      grade: "", // blank for student input
      contactHours: c.contactHours || (c.credits * 1),
    })),
  }));
}
